//! The latency that the gate measured on the GB10 (milestone 37 step 11), in milliseconds: the wall time of a call of the
//! engine in a slot filled to `positions` with seeded rows. The ceiling of each cell is `ceiling_ms`. The model of
//! `bound` is above each cell (`tests/bound_model.rs`).
//!
//! Source: `cuda_latency`, 2026-11-24, one GB10, the cache formats `f32`, `bf16` and `e4m3`. Each cell is the largest
//! of the times of one call in two or three runs, after a warm-up call at the same position.

#![allow(dead_code)]

use nagaya_mk_cuda::attn::CacheFormat;

/// One measured call: the format, the positions before the call, the cycles, the rows and the time in milliseconds.
pub struct Cell {
    pub format: CacheFormat,
    pub positions: usize,
    pub cycles: u8,
    pub rows: usize,
    pub ms: u64,
}

/// The ceiling of a cell: the measure plus 20% and 25 ms. The same block in two runs differed by up to 14% (`bf16` at
/// 524,288 positions and 5 cycles took 7,698 and 6,856 ms), so the margin is above that. The 25 ms cover the jitter of
/// the host in a call of 30 ms.
pub fn ceiling_ms(measured: u64) -> u64 {
    measured * 120 / 100 + 25
}

