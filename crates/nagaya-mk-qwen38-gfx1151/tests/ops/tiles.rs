/// A guard on the test itself: the gate and up columns differ (the up matrices are the second half of the pool) and follow
/// the bytes of the expert. A harness that ignored either would make the identity above empty.
#[test]
fn gu_matmul_sees_the_weights() {
    let pool = &*GU_POOL;
    let mut counts = vec![0u32; 512];
    counts[3] = 1;
    counts[4] = 1;
    let x = x_of(9950, 2, GU_K);
    let gu = moe_gu(pool, &counts, &x, 1, 0, true);
    let width = 2 * GU_ROWS;
    let (gate, up): (Vec<f32>, Vec<f32>) = (
        gu.chunks(width).flat_map(|row| row[..GU_ROWS].to_vec()).collect(),
        gu.chunks(width).flat_map(|row| row[GU_ROWS..].to_vec()).collect(),
    );
    assert!(!mkops::same_bits(&gate, &up), "the gate and the up columns are equal");
    let mut other = vec![0u32; 512];
    other[5] = 1;
    other[4] = 1;
    assert!(
        !mkops::same_bits(&gu, &moe_gu(pool, &other, &x, 1, 0, true)),
        "other experts gave the same output"
    );
}
