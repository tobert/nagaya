/// A guard on the test itself: the output of the down stage depends on the bytes of the expert. A harness that ignored the
/// weights, or read the wrong expert, would make every identity above empty.
#[test]
fn down_matmul_sees_the_weights() {
    let pool = &*DOWN_POOL;
    let mut counts = vec![0u32; 512];
    counts[3] = 1;
    counts[4] = 1;
    let h = x_of(9600, 2, DOWN_K);
    let y = moe_down(IQ4_NL, pool, &counts, &[0, 1], &h, 1, 0);
    let swapped = moe_down(IQ4_NL, pool, &counts, &[1, 0], &h, 1, 0);
    assert!(
        !mkops::same_bits(&y, &swapped),
        "swapping the rows did not change the output"
    );
    let mut other = counts.clone();
    other[3] = 0;
    other[4] = 0;
    other[5] = 1;
    other[6] = 1;
    let moved = moe_down(IQ4_NL, pool, &other, &[0, 1], &h, 1, 0);
    assert!(!mkops::same_bits(&y, &moved), "other experts gave the same output");
}

/// `op_moe_gu` over the pool: expert `e < 256` takes `counts[e]` rows of `x` (grouped by expert, in expert order). The result
/// is `[sum counts, 1280]`, gate then up, in grouped order.
fn moe_gu(raw: &[u8], counts: &[u32], x: &[f32], mode: u32, grid: u32, look: bool) -> Vec<f32> {
    let total: u32 = counts.iter().sum();
    assert_eq!(x.len(), total as usize * GU_K);
    assert!(counts[256..].iter().all(|&c| c == 0), "an up matrix is routed");
    let mut gu = vec![f32::NAN; total as usize * 2 * GU_ROWS];
    let library = mkops::lib(if look { "moe" } else { "moe_nolook" });
    let f = crate::sym!(
        library,
        "mk_moe_gu",
        fn(*const c_void, u64, *const c_void, u64, *const c_void, u64, u32, *mut c_void, u64, u32, u32) -> i32
    );
    let rc = unsafe {
        f(
            ptr(raw),
            nbytes(raw),
            ptr(counts),
            nbytes(counts),
            ptr(x),
            nbytes(x),
            total,
            ptr_mut(&mut gu),
            nbytes(&gu),
            mode,
            grid,
        )
    };
    assert_eq!(rc, 0, "mk_moe_gu");
    gu
}

/// The gate and up stage on IQ3_S tiles must not change one output bit against the same stage on GGUF rows. A schedule
/// change of the tile item is held to this. The test runs every routed pass size 1..40, 64 and 100 (only experts below 256
/// are routed, because the second half of the pool holds the up matrices), several grids, and single experts that hold 1..40
/// tokens.
fn gu_tiled_matmul(look: bool) {
    let pool = &*GU_POOL;
    for (n, ntok) in (1usize..=40).chain([64, 100]).enumerate() {
        let counts = routed_counts(1000 + n as u64, ntok, 256);
        let a: u32 = counts.iter().sum();
        let x = x_of(9700 + n as u64, a as usize, GU_K);
        let plain = moe_gu(pool, &counts, &x, 0, 0, true);
        assert_same_finite(
            &plain,
            &moe_gu(pool, &counts, &x, 1, 0, look),
            &format!("pass T={ntok}"),
        );
        if [1, 8, 33].contains(&ntok) {
            for grid in [1, 7, 80] {
                assert_same_finite(
                    &plain,
                    &moe_gu(pool, &counts, &x, 1, grid, look),
                    &format!("T={ntok} grid={grid}"),
                );
            }
        }
    }
    for ntok in 1usize..=40 {
        let mut counts = vec![0u32; 512];
        counts[0] = ntok as u32;
        counts[137] = 1;
        counts[255] = (ntok % 5) as u32 + 1;
        let a: u32 = counts.iter().sum();
        let x = x_of(9800 + ntok as u64, a as usize, GU_K);
        assert_same_finite(
            &moe_gu(pool, &counts, &x, 0, 0, true),
            &moe_gu(pool, &counts, &x, 1, 0, look),
            &format!("experts 0/137/255 with {ntok}"),
        );
    }
}

