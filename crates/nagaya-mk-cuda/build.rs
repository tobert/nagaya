//! Compiles the CUDA C++ persistent megakernel interpreter with `nvcc` ahead of time when the feature `cuda` is on.
//!
//! Each engine gets its own `.cubin` in `OUT_DIR`, embedded via `include_bytes!`. The flags fix float rounding
//! (`--fmad=false`) for reproducible bits and target `sm_121a` for GB10 Blackwell block-scaled MMA instructions.

use std::path::{Path, PathBuf};
use std::process::Command;

#[path = "src/protocol.rs"]
#[allow(dead_code)]
mod protocol;

const ARCH: &str = "sm_121a";

fn find_nvcc() -> PathBuf {
    if let Some(path) = std::env::var_os("CUDA_NVCC") {
        return PathBuf::from(path);
    }
    if let Ok(output) = Command::new("nvcc").arg("--version").output()
        && output.status.success()
    {
        return PathBuf::from("nvcc");
    }
    let default = PathBuf::from("/usr/local/cuda/bin/nvcc");
    if default.is_file() {
        return default;
    }
    panic!(
        "cannot find nvcc. Install the CUDA toolkit, set CUDA_NVCC, add nvcc to PATH, or build without the feature cuda."
    );
}

fn compile_cubin(nvcc: &Path, source: &Path, kernels: &Path, out: &Path, name: &str, defines: &[&str]) {
    let dest = out.join(name);
    let mut cmd = Command::new(nvcc);
    cmd.args(["-cubin", &format!("-arch={ARCH}"), "-std=c++20", "--fmad=false", "-O3"]);
    for def in defines {
        cmd.arg(format!("-D{def}"));
    }
    cmd.arg("-I")
        .arg(kernels)
        .arg("-I")
        .arg(out)
        .arg("-o")
        .arg(&dest)
        .arg(source);
    let output = cmd.output().unwrap_or_else(|e| {
        panic!(
            "cannot run {}: {e}. Check CUDA_NVCC or build without the feature cuda.",
            nvcc.display()
        )
    });
    assert!(
        output.status.success(),
        "nvcc failed to compile {} ({name}) for {ARCH}: {}\n{}",
        source.display(),
        output.status,
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(
        dest.is_file(),
        "nvcc wrote no {}. Read the nvcc output above.",
        dest.display()
    );
}

/// Write `mk_protocol.h`: the opcodes, the flags, the sizes and the offset of each field, all from `src/protocol.rs`.
/// The kernel checks its own structs against these numbers with `static_assert`.
fn protocol_header() -> String {
    use protocol::{BlockStats, MkTaskDescriptor};
    use std::fmt::Write as _;
    use std::mem::{align_of, offset_of, size_of};

    macro_rules! offsets {
        ($out:ident, $prefix:literal, $ty:ty: $($field:ident),*) => {
            $(writeln!($out, "#define {}{} {}", $prefix, stringify!($field), offset_of!($ty, $field)).unwrap();)*
        };
    }
    let mut h = String::from("// Generated by build.rs from src/protocol.rs. Do not edit.\n#pragma once\n\n");
    for (name, value) in protocol::OPCODES.iter().chain(protocol::FLAGS) {
        writeln!(h, "#define {name} {value}u").unwrap();
    }
    writeln!(h, "#define NO_EVENT {}u", protocol::NO_EVENT).unwrap();
    writeln!(h, "#define MK_PROFILE_WORDS {}u", protocol::PROFILE_WORDS).unwrap();
    writeln!(h, "#define MK_DESC_BYTES {}", size_of::<MkTaskDescriptor>()).unwrap();
    writeln!(h, "#define MK_DESC_ALIGN {}", align_of::<MkTaskDescriptor>()).unwrap();
    offsets!(h, "MK_DESC_OFF_", MkTaskDescriptor: opcode, flags, layer, wait_event, signal_event, a, b, c, d, p0, p1, p2, p3);
    writeln!(h, "#define MK_STATS_BYTES {}", size_of::<BlockStats>()).unwrap();
    offsets!(h, "MK_STATS_OFF_", BlockStats: tasks_run, pad, wait_ns, exec_ns);
    h
}

fn main() {
    println!("cargo:rerun-if-changed=kernels");
    println!("cargo:rerun-if-changed=src/protocol.rs");
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    std::fs::write(out_dir.join("mk_protocol.h"), protocol_header())
        .unwrap_or_else(|e| panic!("cannot write mk_protocol.h into {}: {e}", out_dir.display()));
    println!("cargo:rerun-if-env-changed=CUDA_NVCC");
    if std::env::var_os("CARGO_FEATURE_CUDA").is_none() {
        return;
    }
    let nvcc = find_nvcc();
    let version_out = Command::new(&nvcc)
        .arg("--version")
        .output()
        .unwrap_or_else(|e| panic!("cannot run {} --version: {e}", nvcc.display()));
    assert!(
        version_out.status.success(),
        "{} --version failed: {}",
        nvcc.display(),
        version_out.status
    );
    let version_text = String::from_utf8_lossy(&version_out.stdout);
    let version = version_text
        .lines()
        .rev()
        .find(|line| !line.trim().is_empty())
        .map(str::trim)
        .unwrap_or("unknown");
    println!("cargo:rustc-env=CUDA_NVCC_VERSION={version}");

    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    let kernels = manifest.join("kernels");
    let source = kernels.join("megakernel.cu");

    compile_cubin(&nvcc, &source, &kernels, &out, "megakernel_inkling2_sm121.cubin", &[]);
    compile_cubin(
        &nvcc,
        &source,
        &kernels,
        &out,
        "megakernel_inkling2_profile_sm121.cubin",
        &["MK_PROFILE"],
    );
    // A cubin with a small spin limit, so that a test can prove that a wait that never ends traps.
    compile_cubin(
        &nvcc,
        &source,
        &kernels,
        &out,
        "megakernel_inkling2_spin_test_sm121.cubin",
        &["MK_SPIN_LIMIT=65536ull"],
    );
    println!("cargo:rustc-link-lib=cuda");
}
